/// (code stored in config.ini, strings)
pub const LANGUAGES: [(&str, &Strings); 10] = [
    ("en", &EN),
    ("zh-Hans", &ZH_HANS),
    ("zh-Hant", &ZH_HANT),
    ("ja", &JA),
    ("ko", &KO),
    ("es", &ES),
    ("fr", &FR),
    ("de", &DE),
    ("pt-BR", &PT_BR),
    ("ru", &RU),
];

static CURRENT: AtomicUsize = AtomicUsize::new(0);

/// Strings of the active language.
pub fn t() -> &'static Strings {
    LANGUAGES[CURRENT.load(Ordering::Relaxed)].1
}

/// Activates the language from the config ("auto" or a code from `LANGUAGES`).
pub fn apply(setting: &str) {
    let index = LANGUAGES
        .iter()
        .position(|(code, _)| code.eq_ignore_ascii_case(setting.trim()))
        .unwrap_or_else(system_language);
    CURRENT.store(index, Ordering::Relaxed);
}

fn system_language() -> usize {
    let id = unsafe { GetUserDefaultUILanguage() };
    let code = match id & 0x3FF {
        0x04 if matches!(id, 0x0404 | 0x0C04 | 0x1404) => "zh-Hant", // Taiwan, Hong Kong, Macao
        0x04 => "zh-Hans",
        0x11 => "ja",
        0x12 => "ko",
        0x0A => "es",
        0x0C => "fr",
        0x07 => "de",
        0x16 => "pt-BR",
        0x19 => "ru",
        _ => "en",
    };
    LANGUAGES.iter().position(|(c, _)| *c == code).unwrap_or(0)
}

/// Replaces `{0}`, `{1}`, ... in `template`.
pub fn fmt(template: &str, args: &[&dyn Display]) -> String {
    let mut s = template.to_string();
    for (i, a) in args.iter().enumerate() {
        s = s.replace(&format!("{{{i}}}"), &a.to_string());
    }
    s
}

